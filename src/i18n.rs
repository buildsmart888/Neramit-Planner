#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn switches_language() {
        set_lang(Lang::English);
        assert_eq!(tr("Task Name"), "Task Name");
        set_lang(Lang::Thai);
        assert_ne!(tr("Task Name"), "Task Name");
        assert_eq!(tr("no such string"), "no such string");
        assert!(trf("Page {} of {}", &["1", "3"]).contains('3'));
        set_lang(Lang::English);
        assert_eq!(trf("Page {} of {}", &["1", "3"]), "Page 1 of 3");
    }

    #[test]
    fn no_duplicate_keys() {
        let mut seen = std::collections::HashSet::new();
        for (k, _) in TH {
            assert!(seen.insert(*k), "duplicate key {k:?}");
        }
    }
}
