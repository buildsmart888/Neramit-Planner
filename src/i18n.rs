//! User-interface language (English / Thai).
//!
//! Source strings are the English labels of the program; `tr` looks them up in the Thai table
//! when Thai is selected (File > Options > Language, or the language button in the title bar).
//! Thai results are returned pre-shaped for display (see `thai.rs`), so they must only be drawn,
//! never stored or compared. Strings without a translation fall back to English.

use std::collections::HashMap;
use std::sync::atomic::{AtomicU8, Ordering};
use std::sync::OnceLock;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    English,
    Thai,
}

static LANG: AtomicU8 = AtomicU8::new(0);

pub fn set_lang(l: Lang) {
    LANG.store(if l == Lang::Thai { 1 } else { 0 }, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    if LANG.load(Ordering::Relaxed) == 1 {
        Lang::Thai
    } else {
        Lang::English
    }
}

pub fn is_thai() -> bool {
    lang() == Lang::Thai
}

/// A Thai user: Thai display language or a Thai Windows locale.
pub fn thai_user() -> bool {
    is_thai() || crate::locale::system().name.starts_with("th")
}

fn table() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| {
        TH.iter()
            .map(|(en, th)| {
                // pre-shape once; the table lives for the whole program
                let shaped: &'static str = Box::leak(crate::thai::shape(th).into_owned().into_boxed_str());
                (*en, shaped)
            })
            .collect()
    })
}

/// `tr` as an owned string.
pub fn trp(s: &str) -> String {
    tr(s).to_string()
}

/// Display text of a UI string in the current language.
pub fn tr(s: &str) -> &str {
    if !is_thai() {
        return s;
    }
    table().get(s).copied().unwrap_or(s)
}

/// Unshaped translation, for files written outside the app (Excel cells, PDF metadata).
pub fn tr_raw(s: &str) -> &str {
    static RAW: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    if !is_thai() {
        return s;
    }
    RAW.get_or_init(|| TH.iter().copied().collect()).get(s).copied().unwrap_or(s)
}

/// `tr` for owned strings (labels produced by enum `label` methods, menu items, ...).
pub fn trs(s: String) -> String {
    if !is_thai() {
        return s;
    }
    match table().get(s.as_str()) {
        Some(t) => t.to_string(),
        None => s,
    }
}

/// Translate a template with `{}` placeholders, then fill them in order.
pub fn trf(template: &str, args: &[&str]) -> String {
    let mut out = String::new();
    let mut it = args.iter();
    let t = tr(template);
    let mut rest = t;
    while let Some(p) = rest.find("{}") {
        out.push_str(&rest[..p]);
        out.push_str(it.next().copied().unwrap_or(""));
        rest = &rest[p + 2..];
    }
    out.push_str(rest);
    out
}

